#!/usr/bin/env node
/**
 * The reference pages, generated from the registries they describe (INV-1659).
 *
 * The hand-written tool table in docs/02 stopped at seven tools while the product grew to fifty:
 * a table somebody has to remember to update is a table that is wrong. The sources are already
 * machine-readable — `buildTools()` and the tiers in side-effects.ts, the starter and hub skills,
 * the catalog shelf, the prompt parts — so the pages are rendered from them, and `npm test`
 * (docs-reference.test.mjs) fails when a page on disk and its rendering disagree, the way
 * docs-lint holds docs/INDEX.md to the headers.
 *
 *   node scripts/docs-reference.mjs           print which pages are stale (exit 1 if any)
 *   node scripts/docs-reference.mjs --check   the same; what the suite runs
 *   node scripts/docs-reference.mjs --write   rewrite the stale pages
 *
 * The pages sit at the top of docs/ as `family: guide` until the manual family exists
 * (INV-1661), which moves them under docs/manual/. Rendering imports TypeScript, so the CLI
 * re-runs itself under `--experimental-transform-types` with the suite's hermetic environment:
 * a tool description that reads a variable must not render differently on one machine.
 */

import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { hermeticEnv } from "./test-env.mjs";

const root = join(fileURLToPath(new URL(".", import.meta.url)), "..");
const src = path => pathToFileURL(join(root, "src", path)).href;

/** Where each page lives, relative to the repository. */
export const PAGES = {
  tools: "docs/reference-tools.md",
  skills: "docs/reference-skills.md",
  templates: "docs/reference-templates.md",
  promptParts: "docs/reference-prompt-parts.md",
};

/** Every connector `buildTools` can be handed, for the all-on combination. */
const CONNECTORS = ["github", "feishu", "dingtalk"];

/** A table cell: one line, no pipe that would end the cell. */
function cell(value) {
  return String(value ?? "").replace(/\s+/g, " ").replace(/\|/g, "\\|").trim();
}

/** The first sentence, which is what a tool or skill description leads with. */
export function firstSentence(text, max = 220) {
  const flat = String(text ?? "").replace(/\s+/g, " ").trim();
  const end = /(?<=[^.]{12}[.!?])\s|(?<=[。！？])/.exec(flat);
  const sentence = end === null ? flat : flat.slice(0, end.index).trim();
  return sentence.length > max ? `${sentence.slice(0, max - 1).trimEnd()}…` : sentence;
}

function header(slug, title, about) {
  return [
    `<!-- doc: ${slug}`,
    `     title: ${title}`,
    "     family: guide",
    "     status: current",
    "     updated: generated",
    "     generated: true",
    "-->",
    `# ${title}`,
    "",
    `Generated by \`scripts/docs-reference.mjs\` from ${about}; \`npm test\` fails when this page`,
    "and the source disagree. Change the source and run `node scripts/docs-reference.mjs --write`.",
    "",
  ];
}

function table(columns, rows) {
  return [`| ${columns.join(" | ")} |`, `|${columns.map(() => "---").join("|")}|`, ...rows.map(row => `| ${row.map(cell).join(" | ")} |`)];
}

/**
 * `buildTools` with every optional tool switched on: a box, vision, a host runner, the desktop,
 * the doc reader, template staging, every connector and a search key. The key is set for the
 * call only; nothing is searched.
 */
export async function allOnTools(overrides = {}) {
  const { buildTools } = await import(src("host/tools.ts"));
  const { SEARCH_PROVIDERS } = await import(src("host/web.ts"));
  const on = { hasBox: true, vision: true, hasHostRunner: true, canUseDesktop: true, hasDocReader: true, canPackTemplate: true, fork: false, connectors: CONNECTORS, search: true, ...overrides };
  const key = SEARCH_PROVIDERS[0].keyEnv;
  const before = process.env[key];
  if (on.search) process.env[key] = "rendering-the-reference";
  else delete process.env[key];
  try {
    return buildTools(on.hasBox, on.vision, undefined, on.hasHostRunner, on.canUseDesktop, on.hasDocReader, on.canPackTemplate, on.fork, on.connectors);
  } finally {
    if (before === undefined) delete process.env[key];
    else process.env[key] = before;
  }
}

/** What withholds a tool: each condition switched off alone, against the all-on list. */
async function conditions(names) {
  const switches = [
    ["a box", { hasBox: false }],
    ["vision", { vision: false }],
    ["a host runner", { hasHostRunner: false }],
    ["the desktop", { canUseDesktop: false }],
    ["the Feishu doc reader", { hasDocReader: false }],
    ["template staging", { canPackTemplate: false }],
    ["a search key", { search: false }],
    ...CONNECTORS.map(connector => [`connector ${connector}`, { connectors: CONNECTORS.filter(c => c !== connector) }]),
    ["any connector", { connectors: [] }],
  ];
  const needs = new Map(names.map(name => [name, []]));
  for (const [label, off] of switches) {
    const offered = new Set((await allOnTools(off)).map(tool => tool.name));
    for (const name of names) if (!offered.has(name)) needs.get(name).push(label);
  }
  // "any connector" only says something when no single connector already did.
  for (const list of needs.values()) if (list.length > 1 && list.includes("any connector")) list.splice(list.indexOf("any connector"), 1);
  const inFork = new Set((await allOnTools({ fork: true })).map(tool => tool.name));
  return new Map(names.map(name => [name, { needs: needs.get(name), fork: inFork.has(name) }]));
}

/** The tier as the gate reads it; per call when the input decides. */
function tierOf(name, sideEffectOf, tierAsks) {
  const plain = sideEffectOf(name, {});
  const reaching = sideEffectOf(name, { method: "POST", connector: "the service", share_with: ["someone"], attendees: ["someone"], assignees: ["someone"] });
  const asks = effect => (tierAsks(effect.tier) ? `yes${effect.action ? `: “${effect.action}”` : ""}` : "no");
  if (plain.tier === reaching.tier && plain.action === reaching.action) return { tier: plain.tier, consent: asks(plain) };
  return { tier: `${plain.tier}, or ${reaching.tier} by call`, consent: `${asks(plain)}; by call ${asks(reaching)}` };
}

async function renderTools() {
  const { sideEffectOf, tierAsks } = await import(src("host/side-effects.ts"));
  const { RESIDENT_TOOLS, GATEWAY_TOOLS } = await import(src("host/tool-roster.ts"));
  const catalog = await import(src("host/catalog.ts"));
  const tools = await allOnTools();
  const names = tools.map(tool => tool.name);
  const when = await conditions(names);
  const toolsets = { desk: catalog.DESK_TOOLS, web: catalog.WEB_TOOLS, code: catalog.CODE_TOOLS, team: catalog.TEAM_TOOLS };
  const rows = [...tools]
    .sort((a, b) => a.name.localeCompare(b.name))
    .map(tool => {
      const { tier, consent } = tierOf(tool.name, sideEffectOf, tierAsks);
      const { needs, fork } = when.get(tool.name);
      const offered = [needs.length === 0 ? "always" : `needs ${needs.join(", ")}`, ...(fork ? [] : ["not in a fork"])].join("; ");
      const roster = RESIDENT_TOOLS.has(tool.name) || GATEWAY_TOOLS.has(tool.name) ? "resident" : "deferred";
      const sets = Object.entries(toolsets).filter(([, list]) => list.includes(tool.name)).map(([set]) => set).join(", ");
      const params = Object.keys(tool.input_schema?.properties ?? {}).map(p => `\`${p}\``).join(", ");
      return [`\`${tool.name}\``, firstSentence(tool.description), tier, consent, offered, roster, sets || "—", params || "—"];
    });
  return [
    ...header("reference-tools", "Reference: the built-in tools", "`buildTools()` (src/host/tools.ts), the tiers in src/host/side-effects.ts, the roster in src/host/tool-roster.ts and the catalog toolsets in src/host/catalog.ts"),
    `${tools.length} tools: the list \`buildTools\` offers with every optional one switched on — a box, vision, a host runner, the desktop, the Feishu doc reader, template staging, a search key and the connectors ${CONNECTORS.join(", ")}. A real turn is offered fewer; **offered** says what each one needs.`,
    "",
    "- **tier** — what a call does to the world (side-effects.ts): `observe` looks, `self` stays in the box or with the person who asked, `reach` acts past the box, `credential` touches authority.",
    "- **asks** — whether the gate asks a person, and the phrase on the consent card. Host-written, never the agent's.",
    "- **roster** — `resident` rides in every turn; `deferred` is found through `FindMcpTool` and called through `UseMcpTool`.",
    "- **toolsets** — which catalog toolsets (desk, web, code, team) an installed expert gets it in.",
    "",
    ...table(["tool", "what it does", "tier", "asks", "offered", "roster", "toolsets", "parameters"], rows),
    "",
  ].join("\n");
}

async function renderSkills() {
  const { starterSkillsWithEvals } = await import(src("host/starter-skills.ts"));
  const { hubSkillSlugs, catalogDataDir } = await import(src("host/catalog.ts"));
  const { parseSkillFile } = await import(src("host/skills.ts"));
  const row = (slug, text, from) => {
    const { meta } = parseSkillFile(text);
    const runs = [meta.schedule ? `schedule \`${meta.schedule}\`` : "", meta.trigger ? `trigger \`${meta.trigger}\`` : ""].filter(Boolean).join("; ");
    return [`\`${slug}\``, meta.name ?? slug, firstSentence(meta.description ?? "", 280), runs || "on request", from];
  };
  const starters = starterSkillsWithEvals().map(s => row(s.slug, s.content, "starter"));
  const hub = hubSkillSlugs().map(slug => row(slug, readFileSync(join(catalogDataDir(), "skills", slug, "SKILL.md"), "utf8"), "hub"));
  const rows = [...starters, ...hub].sort((a, b) => a[0].localeCompare(b[0]));
  return [
    ...header("reference-skills", "Reference: the skills that ship", "`starterSkillsWithEvals()` (src/host/starter-skills.ts) and `hubSkillSlugs()` (src/host/catalog.ts, the packages in src/host/catalog-data/skills)"),
    `${starters.length} starter skills, seeded into every box, and ${hub.length} hub packages, vendored for the catalog experts. **runs** is the skill's own \`schedule:\` or \`trigger:\`; without one it is read when a request matches its description.`,
    "",
    ...table(["slug", "name", "description", "runs", "from"], rows),
    "",
  ].join("\n");
}

async function renderTemplates() {
  const catalog = await import(src("host/catalog.ts"));
  const templates = catalog.shelfTemplates();
  const list = items => (items.length === 0 ? "—" : items.join(", "));
  return [
    ...header("reference-templates", "Reference: the template shelf", "`shelfTemplates()`, `CATALOG_EXPERTS`, `CATALOG_CREWS` and `CATALOG_CONNECTORS` (src/host/catalog.ts)"),
    "## Templates",
    "",
    `${templates.length} ready-made templates (\`lumenbox-template/1\`, src/host/catalog-data/templates): a whole working bot each — persona, memory, skills, routines, connectors.`,
    "",
    ...table(["slug", "name", "title", "skills", "routines", "connectors", "memories"], templates.map(t => [`\`${t.slug}\``, t.name, t.title, t.skills.length, t.routines.length, list(t.connectors), t.memoryCount])),
    "",
    "## Experts",
    "",
    ...table(["slug", "domain", "name", "title", "summary", "tools", "skills"], catalog.CATALOG_EXPERTS.map(e => {
      const set = [["team", catalog.TEAM_TOOLS], ["code", catalog.CODE_TOOLS], ["web", catalog.WEB_TOOLS], ["desk", catalog.DESK_TOOLS]].find(([, tools]) => tools === e.tools)?.[0] ?? `${e.tools.length} tools`;
      return [`\`${e.slug}\``, e.domain, e.name, e.title, e.summary, set, list(e.skills)];
    })),
    "",
    "## Crews",
    "",
    ...table(["slug", "domain", "name", "summary", "members"], catalog.CATALOG_CREWS.map(c => [`\`${c.slug}\``, c.domain, c.name, c.summary, list(c.members)])),
    "",
    "## Connectors",
    "",
    ...table(["slug", "name", "summary", "how it exists here"], catalog.CATALOG_CONNECTORS.map(c => [`\`${c.slug}\``, c.name, c.summary, c.how])),
    "",
  ].join("\n");
}

/** The first paragraph of prose, past the part's own heading. */
function openingProse(text) {
  const paragraphs = text.split(/\n\s*\n/).map(p => p.trim()).filter(p => p !== "" && !/^#/.test(p));
  return (paragraphs[0] ?? "").replace(/^(?:\d+\.|[-*])\s+/, "");
}

async function renderPromptParts() {
  // The prompt module registers each part's default when it loads.
  await import(src("host/prompt.ts"));
  const { parts, hashOf } = await import(src("host/prompt-parts.ts"));
  const all = parts();
  return [
    ...header("reference-prompt-parts", "Reference: the prompt parts", "`parts()` (src/host/prompt-parts.ts), as registered by src/host/prompt.ts"),
    `${all.length} built-in parts. Every one may be overridden by the team: \`~/.agentbox/prompt-overrides/<key>.md\`, whose frontmatter records the **default hash** it was written against; when a release changes the default, the override is marked *default updated* and nothing is merged silently. Only prompt text: no part reaches the policy, the tools or a gate.`,
    "",
    ...table(["key", "title", "what it is for", "default begins", "default size", "default hash", "team may override"], all.map(p => [`\`${p.key}\``, p.title, p.about, firstSentence(openingProse(p.text), 160), `${p.text.split("\n").length} lines`, `\`${hashOf(p.text)}\``, "yes"])),
    "",
  ].join("\n");
}

/** Every page, rendered: `{ path, text }` with the path relative to the repository. */
export async function renderReference() {
  return [
    { path: PAGES.tools, text: await renderTools() },
    { path: PAGES.skills, text: await renderSkills() },
    { path: PAGES.templates, text: await renderTemplates() },
    { path: PAGES.promptParts, text: await renderPromptParts() },
  ];
}

/** The pages whose file on disk is not their rendering. */
export async function stalePages(dir = root) {
  const pages = await renderReference();
  return pages.filter(page => {
    const file = join(dir, page.path);
    return !existsSync(file) || readFileSync(file, "utf8") !== page.text;
  });
}

async function main(args) {
  const stale = await stalePages();
  if (args.includes("--write")) {
    for (const page of stale) writeFileSync(join(root, page.path), page.text);
    console.log(stale.length === 0 ? "reference pages are current" : `wrote ${stale.map(p => p.path).join(", ")}`);
    return 0;
  }
  if (stale.length === 0) {
    console.log("reference pages are current");
    return 0;
  }
  console.error(`stale: ${stale.map(p => p.path).join(", ")}. The source changed; run node scripts/docs-reference.mjs --write and commit the pages.`);
  return 1;
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  if (process.env.AGENTBOX_DOCS_REFERENCE_CHILD === "1") {
    process.exitCode = await main(process.argv.slice(2));
  } else {
    const child = spawnSync(process.execPath, ["--experimental-transform-types", "--no-warnings", fileURLToPath(import.meta.url), ...process.argv.slice(2)], {
      stdio: "inherit",
      env: { ...hermeticEnv(), AGENTBOX_DOCS_REFERENCE_CHILD: "1" },
    });
    process.exitCode = child.status ?? 1;
  }
}
