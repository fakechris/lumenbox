const NEEDS_ZH = { "a box": "一台 box", vision: "视觉", "a host runner": "主机执行器", "the desktop": "桌面", "the Feishu doc reader": "飞书文档阅读器", "template staging": "模板暂存", "a search key": "搜索 key", "any connector": "任一连接器" };
